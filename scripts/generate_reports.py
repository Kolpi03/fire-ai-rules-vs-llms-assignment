def _months(ms: list[int]) -> str:
    """Render the month list recorded in the benchmark config (never a hard-coded label)."""
    names = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
    ms = sorted(ms)
    if ms == list(range(ms[0], ms[-1] + 1)):
        return f"{names[ms[0] - 1]}-{names[ms[-1] - 1]} 2023"
    return ", ".join(names[m - 1] for m in ms) + " 2023"

