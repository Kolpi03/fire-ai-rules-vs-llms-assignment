def load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def pct(x, d=1):
    return "n/a" if x is None else f"{x * 100:.{d}f}%"


def money(x):
    if x is None:
        return "n/a"
    return f"${x:.2e}" if x < 0.01 else f"${x:,.2f}"


def ms(x):
    return "n/a" if x is None else (f"{x:.3f} ms" if x < 1 else f"{x:,.1f} ms")


