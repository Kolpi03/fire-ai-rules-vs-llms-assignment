def _c_refusal_note(bench: dict) -> str:
    n = sum(bench["by_fy"][fy]["llm_compiled_engine"].get("refused_unsupported_input") or 0 for fy in bench["by_fy"])
    return (f" (the approved artifacts refuse {n} per-person 80D cases loudly; the corrected candidates pass every "
            "case and await human approval)") if n else ""


def _eb_summary(bench: dict) -> str:
    e = {fy: bench["by_fy"][fy]["llm_query_engine"] for fy in bench["by_fy"]}
    if any(x.get("rupee_exact_accuracy") is None for x in e.values()):
        return "Engine B not measured (no key) and non-deterministic by construction"
    a, b = e["2024-25"], e["2025-26"]
    return (f"real calls ({a['model']}, n={a['n_cases']}/year): {pct(a['rupee_exact_accuracy'])} / "
            f"{pct(b['rupee_exact_accuracy'])} rupee-exact, deterministic on {a['determinism']['deterministic_cases']}/"
            f"{a['determinism']['cases']} and {b['determinism']['deterministic_cases']}/{b['determinism']['cases']} cases, "
            f"median {ms(a['latency']['median_ms'])}")


def _ex_summary() -> str:
    ex = load(BA / "llm_extractor_eval.json")
    if not ex or not str(ex.get("status", "")).startswith("measured"):
        return "LLM extractor not measured"
    return (f"raw Gemini extractor ({ex['model']}): {ex['complete_cases_correct']} complete cases right, flagged only "
            f"{ex['incomplete_cases_flagged']} cases that need a question (guessed on {ex['counts'].get('guessed', 0)})")


