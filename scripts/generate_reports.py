def _partial_note(agg: dict) -> str:
    notes = []
    for k, v in agg.items():
        if isinstance(v, dict) and v.get("status") != "ok" and v.get("partial_monthly"):
            pm = v["partial_monthly"]
            notes.append(f" `{k}`: {len(pm)}/12 months fetched exactly ({sum(pm.values()):,} rows in those months); "
                         f"missing {', '.join(v.get('months_failed', []))} (NYC API HTTP 503/timeouts), so no full-year "
                         "total is reported (`project_b/data/processed/missing_latitude_monthly.json`).")
    return "".join(notes)


def _stage4_text(st: dict) -> str:
    if st.get("stage4") != "measured":
        return f"* Stage 4 (LLM): {st.get('stage4', 'not run')}."
    sem = list(st["before_llm"])
    rows = "; ".join(f"{p}: recall {fmt(st['before_llm'][p]['recall'])} -> {fmt(st['after_llm'][p]['recall'])}, "
                     f"precision {fmt(st['before_llm'][p]['precision'])} -> {fmt(st['after_llm'][p]['precision'])} "
                     f"({st['good_vetoes_false_alarms_removed'][p]} false alarms removed, "
                     f"{st['bad_vetoes_detections_lost'][p]} true detections lost)" for p in sem)
    good = sum(st["good_vetoes_false_alarms_removed"].values())
    bad = sum(st["bad_vetoes_detections_lost"].values())
    return (f"* **Stage 4 (LLM confirm/veto) measured with real calls** (`{st['model']}`, {st['llm_calls']} calls, "
            f"{st['rows_reviewed']} flagged rows reviewed on the same {st['n_batches']} mixed batches, "
            f"${st['cost_usd_list_price']:.3f} at list price, {st['latency_ms_per_call']:,.0f} ms per call): {rows}. "
            f"In total the LLM removed {good} false alarms but discarded {bad} correct detections, so **stage 4 is "
            "disabled in the shipped pipeline**; the metrics above are stages 0-3 only.")


